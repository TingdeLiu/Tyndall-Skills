def cmd_search(args) -> None:
    vault = resolve_vault(args.vault)
    require_vault(vault)
    words = [w.lower() for w in args.words]
    kinds = [args.type] if args.type else list(TYPE_DIR)
    results = []
    for kind in kinds:
        for path in sorted((vault / TYPE_DIR[kind]).glob("*.md")):
            try:
                text = path.read_text(encoding="utf-8")
            except (OSError, UnicodeDecodeError):
                continue
            meta, body = split_frontmatter(text)
            if args.person:
                hit = (
                    matches_person(meta, args.person)
                    or meta.get("to") == args.person
                    or (kind == "person" and path.stem == args.person)
                    or (not is_self(args.person) and f"[[{args.person}]]" in body)
                )
                if not hit:
                    continue
            if args.no_private and is_private(meta):
                continue
            if args.tag and args.tag not in as_list(meta.get("tags")):
                continue
            haystack = (path.stem + "\n" + text).lower()
            if not all(w in haystack for w in words):
                continue
            snippet = ""
            if words:
                flat = re.sub(r"\s+", " ", body)
                pos = flat.lower().find(words[0])
                if pos >= 0:
                    snippet = flat[max(0, pos - 40):pos + 60].strip()
            results.append(
                {
                    "id": path.stem,
                    "path": path.relative_to(vault).as_posix(),
                    "type": kind,
                    "title": meta.get("title") or meta.get("name") or path.stem,
                    "summary": meta.get("summary", ""),
                    "event_date": meta.get("event_date", ""),
                    "recorded": meta.get("recorded", ""),
                    "narrator": meta.get("narrator", ""),
                    "people": as_list(meta.get("people")),
                    "snippet": snippet,
                    "private": is_private(meta),
                }
            )
    results.sort(key=lambda r: r["recorded"], reverse=True)
    emit({"count": len(results), "results": results[: args.limit]})


# ---------------------------------------------------------------------- check

def cmd_check(args) -> None:
    vault = resolve_vault(args.vault)
    require_vault(vault)
    t = TEXT[vault_language(vault)]
    issues: list[dict] = []
    fixed: list[str] = []

    memories = read_entries(vault / "memories")
    people_dir = vault / "people"

    # 1. Required fields per type.
    for sub, kind in (("memories", "memory"), ("people", "person"), ("capsules", "capsule")):
        for stem, meta in read_entries(vault / sub):
            if not meta:
                issues.append({"file": f"{sub}/{stem}.md", "problem": "no frontmatter"})
                continue
            missing = [k for k in REQUIRED[kind] if not meta.get(k)]
            if missing:
                issues.append({"file": f"{sub}/{stem}.md", "problem": "missing fields: " + ", ".join(missing)})

    # 2. People referenced by memories but without a profile.
    # Someone named only in private memories may have no profile (cmd_add never creates one).
    referenced: dict[str, list[str]] = {}
    public_names: set[str] = set()
    private_names: dict[str, set[str]] = {}
    for stem, meta in memories:
        for person in linked_people(meta):
            referenced.setdefault(person, []).append(stem)
            if is_private(meta):
                private_names.setdefault(stem, set()).add(person)
            else:
                public_names.add(person)
    for person, stems in sorted(referenced.items()):
        if (people_dir / f"{person}.md").exists() or person not in public_names:
            continue
        if args.fix:
            create_person_stub(vault, person, t, stems)
            fixed.append(f"created people/{person}.md")
        else:
            issues.append({"file": f"people/{person}.md", "problem": f"profile missing (mentioned in {len(stems)} memories)"})

    # 3. Backlinks: every memory that lists a person should appear in that person's profile.
    for person, stems in sorted(referenced.items()):
        path = people_dir / f"{person}.md"
        if not path.exists():
            continue
        text = path.read_text(encoding="utf-8")
        for stem in stems:
            if f"[[{stem}]]" in text:
                continue
            if args.fix:
                add_backlink(path, stem, t)
                fixed.append(f"linked [[{stem}]] in people/{person}.md")
            else:
                issues.append({"file": f"people/{person}.md", "problem": f"missing backlink to [[{stem}]]"})

    # 4. Broken [[links]] anywhere in the vault.
    all_stems = {p.stem for sub in SUBDIRS for p in (vault / sub).glob("*.md")}
    headings = {"people": RELATED_HEADINGS, "memories": MEMORY_RELATED_HEADINGS}

    def broken_links(path: Path) -> list[str]:
        allowed = all_stems | private_names.get(path.stem, set())
        return sorted({link.strip() for link in LINK_RE.findall(path.read_text(encoding="utf-8"))} - allowed)

    for sub in SUBDIRS:
        for path in sorted((vault / sub).glob("*.md")):
            broken = broken_links(path)
            if not broken:
                continue
            if args.fix and sub in headings and drop_links(path, set(broken), headings[sub]):
                fixed.append(f"removed dead links in {sub}/{path.name}")
                broken = broken_links(path)
            if broken:
                issues.append({"file": f"{sub}/{path.name}", "problem": "broken links: " + ", ".join(f"[[{b}]]" for b in broken)})

    # 5. INDEX.md / TIMELINE.md out of date (e.g. a birth year was added to a profile by hand).
    if args.fix:
        build_index(vault, None)
        fixed.append("rebuilt INDEX.md and TIMELINE.md")
    else:
        rendered = render_index(vault, None)
        for name in ("INDEX.md", "TIMELINE.md"):
            path = vault / name
            current = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.exists() else None
            if current != rendered[name]:
                issues.append({"file": name, "problem": "out of date (run `index` or `check --fix`)"})
    emit({"ok": not issues, "issues": issues, "fixed": fixed})


