def cmd_add(args) -> None:
    vault = resolve_vault(args.vault)
    require_vault(vault)
    t = TEXT[vault_language(vault)]

    # Read bytes so stdin is decoded as UTF-8 even where the console code page is not.
    data = sys.stdin.buffer.read() if args.draft == "-" else Path(args.draft).read_bytes()
    try:
        raw = data.decode("utf-8-sig")
    except UnicodeDecodeError:
        sys.exit("error: the draft must be UTF-8 text")
    meta, body = split_frontmatter(raw)
    if not meta:
        sys.exit("error: draft has no frontmatter (it must start with a --- block)")

    kind = meta.get("type", "memory")
    if kind not in TYPE_DIR:
        sys.exit(f"error: unknown type '{kind}' (expected memory, person or capsule)")
    meta["type"] = kind
    meta["schema"] = SCHEMA
    if kind in ("memory", "capsule"):
        meta.setdefault("recorded", today())
        if not meta.get("recorded"):
            meta["recorded"] = today()
    if kind == "capsule":
        meta["status"] = meta.get("status") or "draft"
        if meta.get("deliver_mode") and meta["deliver_mode"] not in DELIVER_MODES:
            sys.exit(f"error: deliver_mode must be one of {sorted(DELIVER_MODES)}")
    if kind == "memory" and meta.get("year") and not YEAR_RE.fullmatch(str(meta["year"]).rstrip("s")):
        sys.exit("error: year must be a 4-digit year such as 1995 (or a decade such as 1990s)")
    for key in LIST_KEYS:
        if key in meta:
            meta[key] = [safe_name(v) if key == "people" else v for v in as_list(meta[key])]

    missing = [k for k in REQUIRED[kind] if not meta.get(k)]
    if missing:
        sys.exit(f"error: missing required field(s): {', '.join(missing)}")

    folder = vault / TYPE_DIR[kind]
    if kind == "person":
        stem = safe_name(meta["name"])
        if (folder / f"{stem}.md").exists():
            sys.exit(f"error: person already exists: people/{stem}.md (edit that file instead)")
    else:
        title = safe_name(meta["title"])
        if not title:
            sys.exit("error: title is empty after removing characters not allowed in file names")
        stem = unique_stem(folder, f"{meta['recorded']}-{title}")

    body = body.strip("\n")
    people = linked_people(meta) if kind == "memory" else []
    duplicates = similar_memories(vault, meta) if kind == "memory" else []
    if people and not any(f"[[{p}]]" in body for p in people):
        links = t["sep"].join(f"[[{p}]]" for p in people)
        body += f"\n\n{t['related']}\n\n{t['related_people'].format(links)}"

    target = folder / f"{stem}.md"
    report = {
        "written": target.relative_to(vault).as_posix(),
        "id": stem,
        "people_created": [],
        "backlinks_added": [],
        "possible_duplicates": duplicates,
        "dry_run": args.dry_run,
    }
    if args.dry_run:
        report["people_created"] = [p for p in people if not (vault / "people" / f"{p}.md").exists()]
        report["backlinks_added"] = [p for p in people if p not in report["people_created"]]
        emit(report)
        return

    target.write_text(dump_frontmatter(meta) + "\n" + body + "\n", encoding="utf-8")
    for person in people:
        person_path = vault / "people" / f"{person}.md"
        if person_path.exists():
            if add_backlink(person_path, stem, t):
                report["backlinks_added"].append(person)
        else:
            create_person_stub(vault, person, t, [stem])
            report["people_created"].append(person)

    build_index(vault, None)
    emit(report)


# --------------------------------------------------------------------- remove

def cmd_remove(args) -> None:
    vault = resolve_vault(args.vault)
    require_vault(vault)
    stem = args.id[:-3] if args.id.endswith(".md") else args.id
    stem = Path(stem).name
    path = find_entry(vault, stem)
    if not path:
        sys.exit(f"error: no entry with id '{stem}' in memories/, people/ or capsules/")

    trash = vault / TRASH_DIR / path.parent.name
    trash.mkdir(parents=True, exist_ok=True)
    dest = trash / f"{unique_stem(trash, stem)}.md"
    shutil.move(str(path), str(dest))

    cleaned = [p.stem for p in sorted((vault / "people").glob("*.md")) if drop_links(p, {stem})]
    build_index(vault, None)
    emit(
        {
            "moved_to_trash": dest.relative_to(vault).as_posix(),
            "backlinks_removed_from": cleaned,
            "note": "Other files that still mention [[%s]] are listed by `check`." % stem,
        }
    )


# --------------------------------------------------------------------- search

def cmd_search(args) -> None:
    vault = resolve_vault(args.vault)
    require_vault(vault)
    words = [w.lower() for w in args.words]
    kinds = [args.type] if args.type else list(TYPE_DIR)
    results = []
    for kind in kinds:
        for path in sorted((vault / TYPE_DIR[kind]).glob("*.md")):
            try:
                text = path.read_text(encoding="utf-8")
            except (OSError, UnicodeDecodeError):
                continue
            meta, body = split_frontmatter(text)
            if args.person:
                names = linked_people(meta) + ([meta.get("to")] if meta.get("to") else [])
                if kind == "person":
                    names.append(path.stem)
                if args.person not in names and f"[[{args.person}]]" not in body:
                    continue
            if args.no_private and is_private(meta):
                continue
            if args.tag and args.tag not in as_list(meta.get("tags")):
                continue
            haystack = (path.stem + "\n" + text).lower()
            if not all(w in haystack for w in words):
                continue
            snippet = ""
            if words:
                flat = re.sub(r"\s+", " ", body)
                pos = flat.lower().find(words[0])
                if pos >= 0:
                    snippet = flat[max(0, pos - 40):pos + 60].strip()
            results.append(
                {
                    "id": path.stem,
                    "path": path.relative_to(vault).as_posix(),
                    "type": kind,
                    "title": meta.get("title") or meta.get("name") or path.stem,
                    "summary": meta.get("summary", ""),
                    "event_date": meta.get("event_date", ""),
                    "recorded": meta.get("recorded", ""),
                    "people": as_list(meta.get("people")),
                    "snippet": snippet,
                    "private": is_private(meta),
                }
            )
    results.sort(key=lambda r: r["recorded"], reverse=True)
    emit({"count": len(results), "results": results[: args.limit]})


# ---------------------------------------------------------------------- check

def cmd_check(args) -> None:
    vault = resolve_vault(args.vault)
    require_vault(vault)
    t = TEXT[vault_language(vault)]
    issues: list[dict] = []
    fixed: list[str] = []

    memories = read_entries(vault / "memories")
    people_dir = vault / "people"

    # 1. Required fields per type.
    for sub, kind in (("memories", "memory"), ("people", "person"), ("capsules", "capsule")):
        for stem, meta in read_entries(vault / sub):
            if not meta:
                issues.append({"file": f"{sub}/{stem}.md", "problem": "no frontmatter"})
                continue
            missing = [k for k in REQUIRED[kind] if not meta.get(k)]
            if missing:
                issues.append({"file": f"{sub}/{stem}.md", "problem": "missing fields: " + ", ".join(missing)})

    # 2. People referenced by memories but without a profile.
    referenced: dict[str, list[str]] = {}
    for stem, meta in memories:
        for person in linked_people(meta):
            referenced.setdefault(person, []).append(stem)
    for person, stems in sorted(referenced.items()):
        if (people_dir / f"{person}.md").exists():
            continue
        if args.fix:
            create_person_stub(vault, person, t, stems)
            fixed.append(f"created people/{person}.md")
        else:
            issues.append({"file": f"people/{person}.md", "problem": f"profile missing (mentioned in {len(stems)} memories)"})

    # 3. Backlinks: every memory that lists a person should appear in that person's profile.
    for person, stems in sorted(referenced.items()):
        path = people_dir / f"{person}.md"
        if not path.exists():
            continue
        text = path.read_text(encoding="utf-8")
        for stem in stems:
            if f"[[{stem}]]" in text:
                continue
            if args.fix:
                add_backlink(path, stem, t)
                fixed.append(f"linked [[{stem}]] in people/{person}.md")
            else:
                issues.append({"file": f"people/{person}.md", "problem": f"missing backlink to [[{stem}]]"})

    # 4. Broken [[links]] anywhere in the vault.
    all_stems = {p.stem for sub in SUBDIRS for p in (vault / sub).glob("*.md")}
    for sub in SUBDIRS:
        for path in sorted((vault / sub).glob("*.md")):
            broken = sorted({link.strip() for link in LINK_RE.findall(path.read_text(encoding="utf-8"))} - all_stems)
            if not broken:
                continue
            if args.fix and sub == "people" and drop_links(path, set(broken)):
                fixed.append(f"removed dead links in {sub}/{path.name}")
                broken = sorted({l.strip() for l in LINK_RE.findall(path.read_text(encoding="utf-8"))} - all_stems)
            if broken:
                issues.append({"file": f"{sub}/{path.name}", "problem": "broken links: " + ", ".join(f"[[{b}]]" for b in broken)})

    if args.fix:
        build_index(vault, None)
        fixed.append("rebuilt INDEX.md")
    emit({"ok": not issues, "issues": issues, "fixed": fixed})


# ---------------------------------------------------------------------- stats

def cmd_stats(args) -> None:
    vault = resolve_vault(args.vault)
    require_vault(vault)
    memories = read_entries(vault / "memories")
    people = read_entries(vault / "people")
    capsules = read_entries(vault / "capsules")

    narrators: dict[str, int] = {}
    mentions: dict[str, int] = {}
    for _, meta in memories:
        n = meta.get("narrator") or "我"
        narrators[n] = narrators.get(n, 0) + 1
        for p in linked_people(meta):
            mentions[p] = mentions.get(p, 0) + 1

    known = {stem for stem, _ in people}
    missing_people = sorted(p for p in mentions if p not in known)

    # What still needs filling in: empty profile.md sections, people with no intro yet.
    stubs = {TEXT["zh"]["person_stub"], TEXT["en"]["person_stub"]}
    profile_empty: list[str] = []
    profile_path = vault / "profile.md"
    if profile_path.exists():
        pmeta, pbody = split_frontmatter(profile_path.read_text(encoding="utf-8"))
        if not pmeta.get("name"):
            profile_empty.append("name")
        profile_empty += [h for h, text in section_texts(pbody).items() if h and not text]
    people_need_intro = []
    for path in sorted((vault / "people").glob("*.md")):
        intro = section_texts(split_frontmatter(path.read_text(encoding="utf-8"))[1]).get("", "")
        if not intro or intro in stubs:
            people_need_intro.append(path.stem)

    emit(
        {
            "vault": vault.as_posix(),
            "memories": len(memories),
            "people": len(people),
            "capsules": len(capsules),
            "private": sum(1 for _, m in memories if is_private(m)),
            "undated": sum(1 for _, m in memories if event_year(m) is None),
            "by_narrator": narrators,
            "most_mentioned": sorted(mentions.items(), key=lambda kv: -kv[1])[:5],
            "people_without_profile": missing_people,
            "profile_empty_sections": profile_empty,
            "people_need_intro": people_need_intro,
        }
    )


def documents_dir() -> Path:
    """The user's real Documents folder (Windows may redirect it, e.g. to OneDrive)."""
    if sys.platform == "win32":
        try:
            import ctypes
            from ctypes import wintypes

            buf = ctypes.create_unicode_buffer(wintypes.MAX_PATH)
            # CSIDL_PERSONAL = 5 (Documents), SHGFP_TYPE_CURRENT = 0
            if ctypes.windll.shell32.SHGetFolderPathW(None, 5, None, 0, buf) == 0 and buf.value:
                return Path(buf.value)
        except (OSError, AttributeError):
            pass
    docs = Path.home() / "Documents"
    return docs if docs.is_dir() else Path.home()


def cmd_suggest(args) -> None:
    name = "我的记忆" if args.language == "zh" else "My Memories"
    print((documents_dir() / name).as_posix())


