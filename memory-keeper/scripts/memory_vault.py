def cmd_remove(args) -> None:
    vault = resolve_vault(args.vault)
    require_vault(vault)
    stem = args.id[:-3] if args.id.endswith(".md") else args.id
    stem = Path(stem).name
    path = find_entry(vault, stem)
    if not path:
        sys.exit(f"error: no entry with id '{stem}' in memories/, people/ or capsules/")

    trash = vault / TRASH_DIR / path.parent.name
    trash.mkdir(parents=True, exist_ok=True)
    dest = trash / f"{unique_stem(trash, stem)}.md"
    shutil.move(str(path), str(dest))

    cleaned = [f"people/{p.name}" for p in sorted((vault / "people").glob("*.md")) if drop_links(p, {stem})]
    cleaned += [
        f"memories/{p.name}" for p in sorted((vault / "memories").glob("*.md"))
        if drop_links(p, {stem}, MEMORY_RELATED_HEADINGS)
    ]
    # Profiles left with no memories and no intro: ask the user whether to remove them too.
    linked = {p for _, m in read_entries(vault / "memories") for p in linked_people(m)}
    stubs = PERSON_STUBS
    orphans = []
    for path in sorted((vault / "people").glob("*.md")):
        intro = section_texts(split_frontmatter(path.read_text(encoding="utf-8"))[1]).get("", "")
        if path.stem not in linked and (not intro or intro in stubs):
            orphans.append(path.stem)
    build_index(vault, None)
    emit(
        {
            "moved_to_trash": dest.relative_to(vault).as_posix(),
            "links_removed_from": cleaned,
            "orphan_people": orphans,
            "note": "Other files that still mention [[%s]] are listed by `check`." % stem,
        }
    )


