def related_section_bounds(lines: list[str], headings: set[str] = RELATED_HEADINGS) -> tuple[int, int] | None:
    """(heading index, end index) of the first section whose heading is in `headings`."""
    for i, line in enumerate(lines):
        if line.strip() in headings:
            end = i + 1
            while end < len(lines) and not lines[end].startswith("## "):
                end += 1
            return i, end
    return None


def add_backlink(person_path: Path, stem: str, t: dict) -> bool:
    """Ensure `- [[stem]]` is listed under the person's related-memories heading."""
    text = person_path.read_text(encoding="utf-8")
    lines = text.rstrip("\n").split("\n")
    bounds = related_section_bounds(lines)
    if bounds:
        start, end = bounds
        if any(f"[[{stem}]]" in line for line in lines[start:end]):
            return False
        insert_at = end
        while insert_at > start + 1 and not lines[insert_at - 1].strip():
            insert_at -= 1
        if insert_at == start + 1:
            lines.insert(insert_at, "")
            insert_at += 1
        lines.insert(insert_at, f"- [[{stem}]]")
    else:
        lines += ["", t["related_memories"], "", f"- [[{stem}]]"]
    write_file(person_path, "\n".join(lines) + "\n")
    return True


def drop_links(path: Path, stems: set[str], headings: set[str] = RELATED_HEADINGS) -> bool:
    """Remove list lines in a related section whose links all point into `stems`.

    A line that also links somewhere still valid (e.g. a people line naming two people) is kept.
    """
    lines = path.read_text(encoding="utf-8").rstrip("\n").split("\n")
    bounds = related_section_bounds(lines, headings)
    if not bounds:
        return False
    start, end = bounds

    def dead(line: str) -> bool:
        links = {link.strip() for link in LINK_RE.findall(line)}
        return line.lstrip().startswith("- ") and bool(links) and links <= stems

    kept = [line for line in lines[start + 1:end] if not dead(line)]
    if len(kept) == end - start - 1:
        return False
    lines[start + 1:end] = kept
    write_file(path, "\n".join(lines) + "\n")
    return True


def ensure_people_line(body: str, people: list[str], t: dict) -> str:
    """Make sure the memory body links its people, inside its existing related section if it has one."""
    if not people or any(f"[[{p}]]" in body for p in people):
        return body
    line = t["related_people"].format(t["sep"].join(f"[[{p}]]" for p in people))
    lines = body.split("\n")
    bounds = related_section_bounds(lines, MEMORY_RELATED_HEADINGS)
    if not bounds:
        return body + f"\n\n{t['related']}\n\n{line}"
    start, _ = bounds
    first = start + 1
    while first < len(lines) and not lines[first].strip():
        first += 1
    lines[start + 1:first] = ["", line]
    return "\n".join(lines)


def create_person_stub(vault: Path, name: str, t: dict, stems: list[str]) -> Path:
    # `relation` is left out: a name alone ("老王", "Grandma Rose") does not say how they are related.
    meta = {"schema": SCHEMA, "type": "person", "name": name}
    body = f"\n{t['person_stub']}\n\n{t['related_memories']}\n\n" + "".join(f"- [[{s}]]\n" for s in stems)
    path = vault / "people" / f"{safe_name(name)}.md"
    write_file(path, dump_frontmatter(meta) + body)
    return path


# ------------------------------------------------------------------------ add

def cmd_add(args) -> None:
    vault = resolve_vault(args.vault)
    require_vault(vault)
    t = TEXT[vault_language(vault)]

    # Read bytes so stdin is decoded as UTF-8 even where the console code page is not.
    data = sys.stdin.buffer.read() if args.draft == "-" else Path(args.draft).read_bytes()
    try:
        raw = data.decode("utf-8-sig")
    except UnicodeDecodeError:
        sys.exit("error: the draft must be UTF-8 text")
    meta, body = split_frontmatter(raw)
    if not meta:
        sys.exit("error: draft has no frontmatter (it must start with a --- block)")

    kind = meta.get("type", "memory")
    if kind not in TYPE_DIR:
        sys.exit(f"error: unknown type '{kind}' (expected memory, person or capsule)")
    meta["type"] = kind
    meta["schema"] = SCHEMA
    if kind in ("memory", "capsule"):
        meta.setdefault("recorded", today())
        if not meta.get("recorded"):
            meta["recorded"] = today()
    if kind == "capsule":
        meta["status"] = meta.get("status") or "draft"
        if meta.get("deliver_mode") and meta["deliver_mode"] not in DELIVER_MODES:
            sys.exit(f"error: deliver_mode must be one of {sorted(DELIVER_MODES)}")
    if kind == "memory" and meta.get("year") and not YEAR_RE.fullmatch(str(meta["year"]).rstrip("s")):
        sys.exit("error: year must be a 4-digit year such as 1995 (or a decade such as 1990s)")
    for key in LIST_KEYS:
        if key in meta:
            meta[key] = [safe_name(v) if key == "people" else v for v in as_list(meta[key])]

    missing = [k for k in REQUIRED[kind] if not meta.get(k)]
    if missing:
        sys.exit(f"error: missing required field(s): {', '.join(missing)}")

    folder = vault / TYPE_DIR[kind]
    if kind == "person":
        stem = safe_name(meta["name"])
        if (folder / f"{stem}.md").exists():
            sys.exit(f"error: person already exists: people/{stem}.md (edit that file instead)")
    else:
        title = safe_name(meta["title"])
        if not title:
            sys.exit("error: title is empty after removing characters not allowed in file names")
        stem = unique_stem(folder, f"{meta['recorded']}-{title}")

    body = body.strip("\n")
    people = linked_people(meta) if kind == "memory" else []
    duplicates = similar_memories(vault, meta) if kind == "memory" else []
    # A private memory never creates a profile: a new people/前妻.md would say what the memory hides.
    skipped = []
    if is_private(meta):
        skipped = [p for p in people if not (vault / "people" / f"{p}.md").exists()]
        people = [p for p in people if p not in skipped]
    if kind == "memory":
        body = ensure_people_line(body, people, t)

    target = folder / f"{stem}.md"
    report = {
        "written": target.relative_to(vault).as_posix(),
        "id": stem,
        "people_created": [],
        "backlinks_added": [],
        "people_skipped_private": skipped,
        "possible_duplicates": duplicates,
        "dry_run": args.dry_run,
    }
    if args.dry_run:
        report["people_created"] = [p for p in people if not (vault / "people" / f"{p}.md").exists()]
        report["backlinks_added"] = [p for p in people if p not in report["people_created"]]
        emit(report)
        return

    write_file(target, dump_frontmatter(meta) + "\n" + body + "\n")
    for person in people:
        person_path = vault / "people" / f"{person}.md"
        if person_path.exists():
            if add_backlink(person_path, stem, t):
                report["backlinks_added"].append(person)
        else:
            create_person_stub(vault, person, t, [stem])
            report["people_created"].append(person)

    build_index(vault, None)
    emit(report)


