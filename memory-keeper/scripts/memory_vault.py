# ---------------------------------------------------------------- frontmatter

FRONTMATTER_RE = re.compile(r"^---\s*\r?\n(.*?)\r?\n---\s*(?:\r?\n|$)", re.S)


def split_frontmatter(text: str) -> tuple[dict, str]:
    """Return (meta, body) for the flat `key: value` / `key: [a, b]` frontmatter."""
    text = text.lstrip("﻿")
    m = FRONTMATTER_RE.match(text)
    if not m:
        return {}, text
    data: dict = {}
    for line in m.group(1).splitlines():
        if not line.strip() or line.lstrip().startswith("#") or ":" not in line:
            continue
        key, _, value = line.partition(":")
        key, value = key.strip(), value.strip()
        if value.startswith("[") and value.endswith("]"):
            items = [v.strip().strip("'\"") for v in re.split(r"[,，、]", value[1:-1])]
            data[key] = [v for v in items if v]
        else:
            data[key] = value.strip("'\"")
    return data, text[m.end():]


def parse_frontmatter(text: str) -> dict:
    return split_frontmatter(text)[0]


def dump_frontmatter(meta: dict) -> str:
    order = KEY_ORDER.get(meta.get("type", ""), ())
    keys = [k for k in order if k in meta] + [k for k in meta if k not in order]
    lines = ["---"]
    for key in keys:
        value = meta[key]
        if isinstance(value, list):
            lines.append(f"{key}: [{', '.join(str(v) for v in value)}]")
        elif value is None or value == "":
            continue
        else:
            lines.append(f"{key}: {value}")
    lines.append("---")
    return "\n".join(lines) + "\n"


def read_entries(folder: Path) -> list[tuple[str, dict]]:
    entries = []
    if not folder.is_dir():
        return entries
    for path in sorted(folder.glob("*.md")):
        try:
            meta = parse_frontmatter(path.read_text(encoding="utf-8"))
        except (OSError, UnicodeDecodeError) as exc:
            print(f"warning: skip {path.name}: {exc}", file=sys.stderr)
            continue
        entries.append((path.stem, meta))
    return entries


def as_list(value) -> list[str]:
    if isinstance(value, list):
        return value
    return [value] if value else []


def safe_name(name: str) -> str:
    name = ILLEGAL_CHARS.sub("", name).strip().strip(".")
    return re.sub(r"\s+", " ", name)


SELF_NARRATORS = {"", "我", "本人", "me", "i", "myself"}
PRIVATE_TAGS = {"私密", "private"}
YEAR_RE = re.compile(r"(1[6-9]\d\d|20\d\d)")


def is_private(meta: dict) -> bool:
    return bool(PRIVATE_TAGS & {t.lower() for t in as_list(meta.get("tags"))})


def event_year(meta: dict) -> int | None:
    """Year for the timeline: the `year` field, else a 4-digit year found in `event_date`."""
    for key in ("year", "event_date"):
        m = YEAR_RE.search(str(meta.get(key) or ""))
        if m:
            return int(m.group(1))
    return None


def linked_people(meta: dict) -> list[str]:
    """Everyone a memory links to: its `people`, plus the narrator when it is not the user."""
    people = list(as_list(meta.get("people")))
    narrator = safe_name(str(meta.get("narrator") or ""))
    if narrator.lower() not in SELF_NARRATORS and narrator not in people:
        people.append(narrator)
    return people


def bigrams(text: str) -> set[str]:
    """Character bigrams, which work for Chinese titles as well as English ones."""
    text = re.sub(r"[\W_]+", "", text.lower())
    if len(text) < 2:
        return {text} if text else set()
    return {text[i:i + 2] for i in range(len(text) - 1)}


def similar_memories(vault: Path, meta: dict, limit: int = 3) -> list[dict]:
    """Existing memories that may tell the same story as `meta` (by title, summary and people)."""
    target = bigrams(f"{meta.get('title', '')}{meta.get('summary', '')}")
    title = safe_name(str(meta.get("title", ""))).lower()
    mine = set(linked_people(meta))
    found = []
    for stem, other in read_entries(vault / "memories"):
        theirs = bigrams(f"{other.get('title', '')}{other.get('summary', '')}")
        score = len(target & theirs) / len(target | theirs) if target and theirs else 0.0
        shared = sorted(mine & set(linked_people(other)))
        same_title = bool(title) and safe_name(str(other.get("title", ""))).lower() == title
        if same_title or score >= 0.35 or (shared and score >= 0.2):
            found.append(
                {
                    "id": stem,
                    "title": other.get("title", ""),
                    "summary": other.get("summary", ""),
                    "narrator": other.get("narrator", ""),
                    "shared_people": shared,
                    "score": round(score, 2),
                    "same_title": same_title,
                }
            )
    found.sort(key=lambda d: (d["same_title"], d["score"]), reverse=True)
    return found[:limit]


def section_texts(body: str) -> dict[str, str]:
    """Map each `## heading` (and '' for text before the first one) to its stripped content."""
    sections, current, buf = {}, "", []
    for line in body.splitlines():
        if line.startswith("## "):
            sections[current] = "\n".join(buf).strip()
            current, buf = line[3:].strip(), []
        else:
            buf.append(line)
    sections[current] = "\n".join(buf).strip()
    return sections


def unique_stem(folder: Path, stem: str) -> str:
    candidate, n = stem, 2
    while (folder / f"{candidate}.md").exists():
        candidate = f"{stem}-{n}"
        n += 1
    return candidate


def find_entry(vault: Path, stem: str) -> Path | None:
    for sub in SUBDIRS:
        path = vault / sub / f"{stem}.md"
        if path.exists():
            return path
    return None


# --------------------------------------------------------------------- config

def load_config() -> dict:
    if not CONFIG_PATH.exists():
        return {}
    return json.loads(CONFIG_PATH.read_text(encoding="utf-8"))


def resolve_vault(arg: str | None) -> Path:
    if arg:
        return Path(arg).expanduser()
    vault = load_config().get("vault_path")
    if not vault:
        sys.exit(f"error: no vault path given and none configured in {CONFIG_PATH}")
    return Path(vault).expanduser()


def vault_language(vault: Path) -> str:
    """Language from the config when it describes this vault, else guessed from README."""
    config = load_config()
    if config.get("language") in TEXT:
        try:
            if Path(config.get("vault_path", "")).expanduser().resolve() == vault.resolve():
                return config["language"]
        except OSError:
            pass
    readme = vault / "README.md"
    if readme.exists() and readme.read_text(encoding="utf-8").startswith("# My Memories"):
        return "en"
    return "zh"


def require_vault(vault: Path) -> None:
    if not vault.is_dir():
        sys.exit(f"error: vault not found: {vault}")


