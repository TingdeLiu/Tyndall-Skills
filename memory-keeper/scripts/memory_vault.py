def render_index(vault: Path, language: str | None = None) -> dict:
    """Render INDEX.md and TIMELINE.md without writing them."""
    t = TEXT[language or vault_language(vault)]
    memories = read_entries(vault / "memories")
    people = read_entries(vault / "people")
    capsules = read_entries(vault / "capsules")

    # Newest event first is hard with fuzzy dates; sort by record date, newest first.
    memories.sort(key=lambda e: (e[1].get("recorded", ""), e[0]), reverse=True)

    # Private memories do not count towards a person's total: the count itself would hint at them.
    mention_count: dict[str, int] = {}
    for _, meta in memories:
        if is_private(meta):
            continue
        for person in linked_people(meta):
            mention_count[person] = mention_count.get(person, 0) + 1

    lines = [
        t["index_title"],
        "",
        t["index_note"],
        "",
        totals_text(t, len(memories), len(people), len(capsules)),
        "",
        t["memories"],
        "",
    ]
    for stem, meta in memories:
        if is_private(meta):
            # Only the (neutral) title: date as told, people, mood and summary all give the story away.
            lines.append(f"- {meta.get('recorded', '?')} · [[{stem}]] · {t['private']}")
            continue
        parts = [meta.get("recorded", "?"), f"[[{stem}]]", t["narrator"].format(narrator_label(meta, t))]
        if meta.get("event_date"):
            parts.append(t["when"].format(meta["event_date"]))
        if as_list(meta.get("people")):
            parts.append(t["sep"].join(narrator_label({"narrator": p}, t) for p in as_list(meta.get("people"))))
        if meta.get("mood"):
            parts.append(meta["mood"])
        line = "- " + " · ".join(parts)
        if meta.get("summary"):
            line += f" — {meta['summary']}"
        lines.append(line)

    lines += ["", t["people"], ""]
    for stem, meta in people:
        relation = meta.get("relation") or ""
        if relation == stem:
            relation = ""
        lines.append(f"- [[{stem}]]" + (f" · {relation}" if relation else "") + " · " + count_text(t, mention_count.get(stem, 0)))

    lines += ["", t["capsules"], ""]
    for stem, meta in capsules:
        deliver = " ".join(x for x in (meta.get("deliver_mode", ""), meta.get("deliver_value", "")) if x)
        lines.append(
            f"- [[{stem}]] · " + t["to"].format(meta.get("to") or "?")
            + (f" · {deliver}" if deliver else "")
            + f" · {meta.get('status') or 'draft'}"
            + (f" · {t['private']}" if is_private(meta) else "")
        )

    return {
        "INDEX.md": "\n".join(lines) + "\n",
        "TIMELINE.md": render_timeline(t, memories, people),
        "memories": memories,
        "people": people,
        "capsules": capsules,
    }


def build_index(vault: Path, language: str | None = None) -> dict:
    result = render_index(vault, language)
    for name in ("INDEX.md", "TIMELINE.md"):
        write_file(vault / name, result[name])
    return result


def when_text(meta: dict) -> str:
    """`event_date` as told, with the `year` field added when the date itself has no year."""
    told, year = str(meta.get("event_date") or ""), str(meta.get("year") or "")
    if told and year and not YEAR_RE.search(told):
        return f"{told} ({year})"
    return told or year


def timeline_items(memories: list, people: list, person: str | None = None) -> list[dict]:
    """Memories (and known births) ordered by event year; items without a year come last."""
    items = []
    for stem, meta in memories:
        if person and not matches_person(meta, person):
            continue
        items.append(
            {
                "id": stem,
                "path": f"memories/{stem}.md",
                "kind": "memory",
                "year": event_year(meta),
                "when": when_text(meta),
                "title": meta.get("title", stem),
                "narrator": meta.get("narrator", ""),
                "summary": meta.get("summary", ""),
                "private": is_private(meta),
            }
        )
    for stem, meta in people:
        year = event_year({"year": meta.get("birth")})
        if year and (not person or person == stem):
            items.append({"id": stem, "path": f"people/{stem}.md", "kind": "birth", "year": year,
                          "when": str(meta.get("birth")), "title": stem, "narrator": "", "summary": "",
                          "private": False})
    items.sort(key=lambda d: (d["year"] is None, d["year"] or 0, d["kind"] != "birth", d["id"]))
    return items


def render_timeline(t: dict, memories: list, people: list) -> str:
    lines = [t["timeline_title"], "", t["timeline_note"]]
    heading = None
    for item in timeline_items(memories, people):
        new_heading = t["unknown"] if item["year"] is None else t["decade"].format(item["year"] // 10 * 10)
        if new_heading != heading:
            lines += ["", new_heading, ""]
            heading = new_heading
        if item["kind"] == "birth":
            lines.append(f"- {item['when']} · " + t["born"].format(item["id"]))
            continue
        if item["private"]:
            # The decade heading already places it; the date as told could give the story away.
            lines.append(f"- [[{item['id']}]] · {t['private']}")
            continue
        parts = [item["when"]] if item["when"] else []
        parts += [f"[[{item['id']}]]", t["narrator"].format(narrator_label(item, t))]
        line = "- " + " · ".join(parts)
        if item["summary"]:
            line += f" — {item['summary']}"
        lines.append(line)
    return "\n".join(lines) + "\n"


def cmd_timeline(args) -> None:
    vault = resolve_vault(args.vault)
    require_vault(vault)
    items = timeline_items(read_entries(vault / "memories"), read_entries(vault / "people"), args.person)
    emit({"count": len(items), "undated": sum(1 for i in items if i["year"] is None), "items": items})


def cmd_index(args) -> None:
    vault = resolve_vault(args.vault)
    require_vault(vault)
    result = build_index(vault)
    emit(
        {
            "updated": ["INDEX.md", "TIMELINE.md"],
            "memories": len(result["memories"]),
            "people": len(result["people"]),
            "capsules": len(result["capsules"]),
        }
    )


