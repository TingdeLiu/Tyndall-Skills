def cmd_init(args) -> None:
    vault = Path(args.vault).expanduser().resolve()
    vault.mkdir(parents=True, exist_ok=True)
    for sub in SUBDIRS:
        (vault / sub).mkdir(exist_ok=True)

    zh = args.language == "zh"
    write_if_missing(vault / "README.md", README_ZH if zh else README_EN)
    write_if_missing(
        vault / "profile.md",
        f"---\nschema: {SCHEMA}\ntype: profile\nname:\n---\n\n"
        + ("## 关于我\n\n\n## 说话方式\n" if zh else "## About me\n\n\n## How I talk\n"),
    )

    config = load_config()
    config.update(
        {
            "schema": SCHEMA,
            "vault_path": vault.as_posix(),
            "auto_save": bool(args.auto_save or config.get("auto_save", False)),
            "language": args.language,
        }
    )
    config.setdefault("created", today())
    CONFIG_PATH.parent.mkdir(parents=True, exist_ok=True)
    CONFIG_PATH.write_text(json.dumps(config, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    build_index(vault, args.language)
    print(f"vault ready: {vault}")
    print(f"config written: {CONFIG_PATH}")


def write_if_missing(path: Path, content: str) -> None:
    if not path.exists():
        path.write_text(content, encoding="utf-8")


# ---------------------------------------------------------------------- index

def build_index(vault: Path, language: str | None = None) -> dict:
    t = TEXT[language or vault_language(vault)]
    memories = read_entries(vault / "memories")
    people = read_entries(vault / "people")
    capsules = read_entries(vault / "capsules")

    # Newest event first is hard with fuzzy dates; sort by record date, newest first.
    memories.sort(key=lambda e: (e[1].get("recorded", ""), e[0]), reverse=True)

    mention_count: dict[str, int] = {}
    for _, meta in memories:
        for person in linked_people(meta):
            mention_count[person] = mention_count.get(person, 0) + 1

    lines = [
        t["index_title"],
        "",
        t["index_note"],
        "",
        t["totals"].format(m=len(memories), p=len(people), c=len(capsules)),
        "",
        t["memories"],
        "",
    ]
    for stem, meta in memories:
        parts = [meta.get("recorded", "?"), f"[[{stem}]]", t["narrator"].format(meta.get("narrator") or t["me"])]
        if meta.get("event_date"):
            parts.append(t["when"].format(meta["event_date"]))
        if as_list(meta.get("people")):
            parts.append(t["sep"].join(as_list(meta.get("people"))))
        if meta.get("mood"):
            parts.append(meta["mood"])
        line = "- " + " · ".join(parts)
        if is_private(meta):
            line += f" — {t['private_summary']}"
        elif meta.get("summary"):
            line += f" — {meta['summary']}"
        lines.append(line)

    lines += ["", t["people"], ""]
    for stem, meta in people:
        relation = meta.get("relation") or ""
        count = mention_count.get(stem, 0)
        lines.append(f"- [[{stem}]]" + (f" · {relation}" if relation else "") + " · " + t["count"].format(count))

    lines += ["", t["capsules"], ""]
    for stem, meta in capsules:
        deliver = " ".join(x for x in (meta.get("deliver_mode", ""), meta.get("deliver_value", "")) if x)
        lines.append(
            f"- [[{stem}]] · " + t["to"].format(meta.get("to") or "?")
            + (f" · {deliver}" if deliver else "")
            + f" · {meta.get('status') or 'draft'}"
        )

    (vault / "INDEX.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    build_timeline(vault, t, memories, people)
    return {"memories": memories, "people": people, "capsules": capsules, "mentions": mention_count}


def when_text(meta: dict) -> str:
    """`event_date` as told, with the `year` field added when the date itself has no year."""
    told, year = str(meta.get("event_date") or ""), str(meta.get("year") or "")
    if told and year and not YEAR_RE.search(told):
        return f"{told} ({year})"
    return told or year


def timeline_items(memories: list, people: list, person: str | None = None) -> list[dict]:
    """Memories (and known births) ordered by event year; items without a year come last."""
    items = []
    for stem, meta in memories:
        if person and person not in linked_people(meta):
            continue
        items.append(
            {
                "id": stem,
                "kind": "memory",
                "year": event_year(meta),
                "when": when_text(meta),
                "title": meta.get("title", stem),
                "narrator": meta.get("narrator", ""),
                "summary": meta.get("summary", ""),
                "private": is_private(meta),
            }
        )
    for stem, meta in people:
        year = event_year({"year": meta.get("birth")})
        if year and (not person or person == stem):
            items.append({"id": stem, "kind": "birth", "year": year, "when": str(meta.get("birth")),
                          "title": stem, "narrator": "", "summary": "", "private": False})
    items.sort(key=lambda d: (d["year"] is None, d["year"] or 0, d["kind"] != "birth", d["id"]))
    return items


def build_timeline(vault: Path, t: dict, memories: list, people: list) -> None:
    lines = [t["timeline_title"], "", t["timeline_note"]]
    heading = None
    for item in timeline_items(memories, people):
        new_heading = t["unknown"] if item["year"] is None else t["decade"].format(item["year"] // 10 * 10)
        if new_heading != heading:
            lines += ["", new_heading, ""]
            heading = new_heading
        if item["kind"] == "birth":
            lines.append(f"- {item['when']} · " + t["born"].format(item["id"]))
            continue
        parts = [item["when"]] if item["when"] else []
        parts += [f"[[{item['id']}]]", t["narrator"].format(item["narrator"] or t["me"])]
        line = "- " + " · ".join(parts)
        summary = t["private_summary"] if item["private"] else item["summary"]
        if summary:
            line += f" — {summary}"
        lines.append(line)
    (vault / "TIMELINE.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def cmd_timeline(args) -> None:
    vault = resolve_vault(args.vault)
    require_vault(vault)
    items = timeline_items(read_entries(vault / "memories"), read_entries(vault / "people"), args.person)
    emit({"count": len(items), "undated": sum(1 for i in items if i["year"] is None), "items": items})


def cmd_index(args) -> None:
    vault = resolve_vault(args.vault)
    require_vault(vault)
    result = build_index(vault)
    print(
        f"INDEX.md updated: {len(result['memories'])} memories, "
        f"{len(result['people'])} people, {len(result['capsules'])} capsules"
    )


# ------------------------------------------------------------------ backlinks

def related_section_bounds(lines: list[str]) -> tuple[int, int] | None:
    """(heading index, end index) of the person's backlink section, if present."""
    for i, line in enumerate(lines):
        if line.strip() in RELATED_HEADINGS:
            end = i + 1
            while end < len(lines) and not lines[end].startswith("## "):
                end += 1
            return i, end
    return None


def add_backlink(person_path: Path, stem: str, t: dict) -> bool:
    """Ensure `- [[stem]]` is listed under the person's related-memories heading."""
    text = person_path.read_text(encoding="utf-8")
    lines = text.rstrip("\n").split("\n")
    bounds = related_section_bounds(lines)
    if bounds:
        start, end = bounds
        if any(f"[[{stem}]]" in line for line in lines[start:end]):
            return False
        insert_at = end
        while insert_at > start + 1 and not lines[insert_at - 1].strip():
            insert_at -= 1
        if insert_at == start + 1:
            lines.insert(insert_at, "")
            insert_at += 1
        lines.insert(insert_at, f"- [[{stem}]]")
    else:
        lines += ["", t["related_memories"], "", f"- [[{stem}]]"]
    person_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return True


def drop_links(path: Path, stems: set[str]) -> bool:
    """Remove list lines in a related-memories section that link to any of `stems`."""
    lines = path.read_text(encoding="utf-8").rstrip("\n").split("\n")
    bounds = related_section_bounds(lines)
    if not bounds:
        return False
    start, end = bounds
    kept = [
        line for line in lines[start + 1:end]
        if not (line.lstrip().startswith("- ") and set(LINK_RE.findall(line)) & stems)
    ]
    if len(kept) == end - start - 1:
        return False
    lines[start + 1:end] = kept
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return True


def create_person_stub(vault: Path, name: str, t: dict, stems: list[str]) -> Path:
    meta = {"schema": SCHEMA, "type": "person", "name": name, "relation": name}
    body = f"\n{t['person_stub']}\n\n{t['related_memories']}\n\n" + "".join(f"- [[{s}]]\n" for s in stems)
    path = vault / "people" / f"{safe_name(name)}.md"
    path.write_text(dump_frontmatter(meta) + body, encoding="utf-8")
    return path


