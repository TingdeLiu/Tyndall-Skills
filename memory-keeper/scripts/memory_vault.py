def cmd_init(args) -> None:
    vault = Path(args.vault).expanduser().resolve()
    vault.mkdir(parents=True, exist_ok=True)
    for sub in SUBDIRS:
        (vault / sub).mkdir(exist_ok=True)

    zh = args.language == "zh"
    write_if_missing(vault / "README.md", README_ZH if zh else README_EN)
    write_if_missing(
        vault / "profile.md",
        f"---\nschema: {SCHEMA}\ntype: profile\nname:\n---\n\n"
        + ("## 关于我\n\n\n## 说话方式\n" if zh else "## About me\n\n\n## How I talk\n"),
    )

    config = load_config()
    config.update(
        {
            "schema": SCHEMA,
            "vault_path": vault.as_posix(),
            "auto_save": bool(args.auto_save or config.get("auto_save", False)),
            "language": args.language,
        }
    )
    config.setdefault("created", today())
    CONFIG_PATH.parent.mkdir(parents=True, exist_ok=True)
    write_file(CONFIG_PATH, json.dumps(config, ensure_ascii=False, indent=2) + "\n")

    build_index(vault, args.language)
    emit({"vault": vault.as_posix(), "config": CONFIG_PATH.as_posix(), "language": args.language})


def write_if_missing(path: Path, content: str) -> None:
    if not path.exists():
        write_file(path, content)


